"""S3 — 처리 시간 (PRD_PoC.md 5.1)

목표: 수작업 대비 1/5 이하.

**분자(PoC 시간)는 실측이고, 분모(수작업 시간)는 가정이다.**
세권 님이 실제로 재 주시면 아래 표 한 곳만 고치면 된다.

가정값은 자동 시간과 **무관하게** 정했다. 자동 시간 × 5 로 거꾸로 만들면
"5배 빨라졌다"가 아니라 "5배로 적어 넣었다"가 되어 측정이 무의미해진다.

쓰는 법:  python -m verify.s3_time
"""
from __future__ import annotations

import json
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
뿌리 = Path(__file__).resolve().parents[1]

# ══════════════════════════════════════════════════════════
# ⚠ 미검증 가정 — 실제로 재면 이 숫자만 바꾼다
# ══════════════════════════════════════════════════════════
수작업_분 = {
    "① 상담 받아 적기": 10,   # 통화하며 이름·생년월일시·고민을 메모
    "② 만세력 뽑기": 5,       # 앱/책으로 음양력·절기 확인해 8글자
    "③ 해석 초안 쓰기": 40,   # A4 한 장 분량을 백지에서 작성
    "④ 다듬어 보내기": 10,    # 문장 손질·오타·발송
}
가정근거 = "일반 상담 1건 기준의 경험적 추정. 실측 아님."

# 자동화 뒤에도 사람이 해야 하는 일 (역시 가정)
검수_분_가정 = 15   # 초안을 읽고 고치는 시간. 실제 값은 S5 가 답한다.

단계짝 = {           # 수작업 단계 ← PoC 의 어느 단계가 대신하는가
    "① 상담 받아 적기": ["① 받아쓰기", "② 항목 추출"],
    "② 만세력 뽑기": ["③ 음양력 변환", "④ 진태양시·서머타임 보정", "⑤ 원국·세운 산출"],
    "③ 해석 초안 쓰기": ["⑥ 사실 블록", "⑦ 초안 생성"],
    "④ 다듬어 보내기": [],
}


def 실측읽기() -> tuple[dict[str, float], list[str]]:
    """out/*/run.json 을 모아 단계별 평균 초를 낸다."""
    합, 건수, 출처 = {}, 0, []
    for p in sorted((뿌리 / "out").glob("*/run.json")):
        d = json.loads(p.read_text(encoding="utf-8"))
        건수 += 1
        출처.append(f"{p.parent.name}({d['합계_초']:.1f}초)")
        for k, v in d["단계별_초"].items():
            합[k] = 합.get(k, 0.0) + v
    from verify.guard import 표본확인
    표본확인("S3 실행 기록(run.json)", 출처, 최소=1)
    return {k: v / 건수 for k, v in 합.items()}, 출처


def main() -> int:
    평균, 출처 = 실측읽기()
    print("S3 — 처리 시간 · 목표 수작업 대비 1/5 이하")
    print(f"실측 표본 {len(출처)}건: {', '.join(출처)}")
    print(f"⚠ 수작업 시간은 실측이 아니라 가정입니다 — {가정근거}\n")

    print(f"{'단계':<20}{'수작업':>10}{'PoC 기계':>12}  대신한 것")
    print("-" * 78)
    수합, 기계합 = 0, 0.0
    for 단계, 분 in 수작업_분.items():
        초 = sum(평균.get(s, 0.0) for s in 단계짝[단계])
        수합 += 분
        기계합 += 초
        대신 = ", ".join(단계짝[단계]) or "— (사람이 계속 함)"
        print(f"{단계:<20}{분:>8}분{초:>10.1f}초  {대신}")
    print("-" * 78)
    print(f"{'합계':<20}{수합:>8}분{기계합:>10.1f}초  ({기계합/60:.2f}분)")

    print(f"\n{'=' * 78}\n■ 두 가지로 읽어야 합니다\n{'=' * 78}")

    배 = 수합 * 60 / 기계합
    print(f"\n[읽기 1] 기계 시간만 — {수합}분 → {기계합:.1f}초   **{배:.0f}배**")
    print("  이 숫자는 크지만 **정직하지 않습니다.** PoC 가 내놓는 것은 초안이고,")
    print("  사람이 읽고 고치는 시간이 빠져 있습니다.")

    사람합 = 기계합 / 60 + 검수_분_가정
    배2 = 수합 / 사람합
    print(f"\n[읽기 2] 사람이 쓰는 시간 — {수합}분 → {사람합:.1f}분   **{배2:.1f}배**")
    print(f"  (기계 {기계합/60:.2f}분 + 검수 {검수_분_가정}분 가정)")
    print(f"  판정: {'통과' if 배2 >= 5 else '미달'} (기준 5배 = 1/5 이하)")

    print(f"\n{'=' * 78}")
    print("■ 이 측정이 답하지 못하는 것")
    print(f"{'=' * 78}")
    for x in [
        f"수작업 {수합}분은 **재 본 적 없는 가정값**입니다. 실측으로 바꿔야 합니다.",
        f"검수 {검수_분_가정}분도 가정입니다. 진짜 값은 S5(초안 품질)가 답합니다.",
        "① 받아쓰기는 텍스트로 넣어 건너뛰었습니다. 실제 음성은 더 걸립니다.",
        "기계 시간의 대부분은 LLM 호출 대기라 망 상태에 따라 흔들립니다.",
    ]:
        print(f"  · {x}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
