"""S6 — 리포트 1건당 원가 (검토의견 §6-3)

시간(S3)은 재면서 **돈은 안 재고 있었다.** 상용 유료 서비스에서 건당 LLM 비용은
마진을 결정한다. 기준에 없으면 "상용 전환 가능"을 수치로 방어할 수 없다.

⚠ **단가는 제가 확인하지 않았습니다.** 아래 값은 공표된 가격을 적어 둔 것이고
   바뀔 수 있습니다. 쓰기 전에 공급자 가격표를 직접 확인하십시오.
   토큰 수는 실측이므로, 단가만 고치면 원가는 바로 다시 나옵니다.

쓰는 법:  python -m verify.s6_cost [--환율 1400]
"""
from __future__ import annotations

import json
import sys
from pathlib import Path

뿌리 = Path(__file__).resolve().parents[1]

# ⚠ 미확인 — 공표 가격(USD / 1M 토큰). 실제 청구액과 다를 수 있다.
단가 = {
    "gpt-4o-mini-2024-07-18": {"in": 0.15, "out": 0.60},
    "gpt-4o-mini": {"in": 0.15, "out": 0.60},
}
단가출처 = "공표 가격표 (미확인 · 2026-09 기준으로 적어 둠)"


def main() -> int:
    환율 = float(next((a.split("=", 1)[1] for a in sys.argv[1:]
                       if a.startswith("--환율=")), 1400))

    기록 = []
    for p in sorted((뿌리 / "out").glob("*/run.json")):
        d = json.loads(p.read_text(encoding="utf-8"))
        토큰 = d.get("토큰") or {}
        if not (토큰.get("in") or 토큰.get("out")):
            continue        # 규칙 기반으로 돌린 건은 토큰이 0이다
        모델 = (d.get("조건") or {}).get("모델", "")
        기록.append((p.parent.name, 모델, 토큰.get("in", 0), 토큰.get("out", 0),
                     d.get("재생성", 0), d.get("생성메모", "")))

    sys.path.insert(0, str(뿌리))
    from verify.guard import 표본확인
    표본확인("S6 토큰 기록", 기록, 최소=1)

    print("=" * 80)
    print("S6 — 리포트 1건당 원가")
    print(f"⚠ 단가는 미확인입니다 — {단가출처}. 토큰 수만 실측입니다.")
    print("=" * 80)
    print(f"\n{'건':<6}{'입력토큰':>10}{'출력토큰':>10}{'재생성':>8}{'원가(원)':>12}  모델")
    print("-" * 80)

    총입, 총출, 총원, 재생성건 = 0, 0, 0.0, 0
    재생성사유 = []
    for 이름, 모델, i, o, 재, 메모 in 기록:
        if 재:
            재생성사유.append((이름, 메모))
        p = 단가.get(모델) or 단가["gpt-4o-mini"]
        원 = (i / 1e6 * p["in"] + o / 1e6 * p["out"]) * 환율
        총입 += i
        총출 += o
        총원 += 원
        재생성건 += 재 > 0
        print(f"{이름:<6}{i:>10,}{o:>10,}{재:>8}{원:>12.2f}  {모델}")
    n = len(기록)
    print("-" * 80)
    print(f"{'평균':<6}{총입//n:>10,}{총출//n:>10,}{'':>8}{총원/n:>12.2f}")
    print(f"{'합계':<6}{총입:>10,}{총출:>10,}{'':>8}{총원:>12.2f}   (n={n}, 환율 {환율:,.0f})")

    print(f"\n{'=' * 80}\n■ 읽는 법\n{'=' * 80}")
    건당 = 총원 / n
    print(f"  리포트 1건당 약 **{건당:.1f}원** (단가가 맞다면)")
    print(f"  1,000건이면 약 {건당 * 1000:,.0f}원 · 10,000건이면 약 {건당 * 10000:,.0f}원")

    print()
    print(f"  재시도율 {재생성건}/{n} = {100*재생성건/n:.0f}%")
    if 재생성사유:
        print("  재생성이 일어난 건과 이유:")
        for 이름, 메모 in 재생성사유:
            오작동 = any(w in 메모 for w in ("암시", "암초", "암묵"))
            print(f"    {이름}  [{'⚠ 오작동' if 오작동 else '정상 작동'}]  {메모}")
        print()
        print("  ※ '정상 작동' 은 모델이 진짜 위험한 문장을 썼고 검사가 막은 것입니다.")
        print("    이 재시도는 없애면 안 됩니다 — 없애면 그 문장이 손님에게 갑니다.")
        print("    없애야 할 것은 '오작동' 쪽뿐입니다 (F-8 → C-11 로 해결).")
    else:
        print("  재생성 없음.")

    print(f"\n{'=' * 80}\n■ 이 측정이 답하지 못하는 것\n{'=' * 80}")
    for x in [
        "단가를 확인하지 않았습니다. 공급자 가격표를 직접 보고 고쳐야 합니다.",
        "STT(Whisper) 비용이 빠져 있습니다 — ① 을 한 번도 안 돌렸습니다.",
        f"표본 {n}건입니다. 상담 길이가 길어지면 입력 토큰이 그만큼 늡니다.",
        "사람 검수 인건비가 빠져 있습니다. 그게 실제로는 훨씬 큽니다.",
    ]:
        print(f"  · {x}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
