# ⑩ A1 자동 탐지 — 빈 집합에서 참이 되는 전칭 양화 (F-14 재발 방지)
#
#    파이썬에서 all([]) 는 True 다. 검사 대상이 비면 "위반 0건 → 통과" 가 된다.
#    새 all() / not any() 가 생기면 **검토 목록에 등록될 때까지 게이트가 실패**한다.
# ══════════════════════════════════════════════════════════
def 전칭양화탐지() -> None:
    from verify.guard import 검토된_전칭

    발견 = []
    for 폴더 in ("verify", "poc"):
        for f in sorted((뿌리 / 폴더).glob("*.py")):
            if f.name in ("selftest_negative.py", "guard.py"):
                continue
            나무 = ast.parse(f.read_text(encoding="utf-8"))
            for n in ast.walk(나무):
                if isinstance(n, ast.Call) and getattr(n.func, "id", "") == "all":
                    발견.append((f"{폴더}/{f.name}", "all", n.lineno))
                if (isinstance(n, ast.UnaryOp) and isinstance(n.op, ast.Not)
                        and isinstance(n.operand, ast.Call)
                        and getattr(n.operand.func, "id", "") == "any"):
                    발견.append((f"{폴더}/{f.name}", "not any", n.lineno))

    등록된파일 = {k[0] for k in 검토된_전칭}
    미등록 = [x for x in 발견 if x[0] not in 등록된파일]
    짝("A1 · 빈 집합에서 참이 되는 전칭 양화가 전부 검토됐는가",
       not 미등록,
       True,
       f"발견 {len(발견)}곳 · 미등록 {len(미등록)}곳"
       + (f" {미등록}  ← guard.py 의 검토된_전칭 에 이유를 적으십시오" if 미등록 else ""))

    # 방어 코드 자체가 동작하는가
    from verify.guard import 모두, 표본없음, 표본확인
    빈통과, 빈맞음, 빈분모 = 모두([])
    짝("A1 · 모두()가 빈 집합을 통과로 치지 않는가",
       모두([True, True])[0],
       not 빈통과,
       f"all([]) 는 {all([])} 이지만 모두([]) 는 {빈통과} (분모 {빈분모})")

    try:
        표본확인("시험", [], 최소=1, 조용히=True)
        멈춤 = False
    except 표본없음:
        멈춤 = True
    짝("A1 · 표본확인()이 빈 표본에서 멈추는가",
       표본확인("시험", [1, 2], 최소=1, 조용히=True) == 2,
       멈춤, "표본 0건이면 검사를 돌리지 않고 멈춘다")


