"""빈 집합 방어 — 유형 A 의 나머지 절반을 막는다

배경
  유형 A(성립하지 않는 시험)가 두 번 나왔고 기제가 달랐다.

    F-15  조건이 리터럴 상수      → AST 로 자동 탐지하게 만들었다
    F-14  검사 대상이 0개         → **이건 아직 자동으로 못 막고 있었다**

  파이썬에서 `all([])` 은 **True** 다. 그래서 검사 대상이 비면
  "위반 0건 → 통과" 가 되고, 아무도 이상하게 여기지 않는다.
  실패할 수 없는 시험이 통과로 기록된다.

이 파일이 하는 일
  ① 표본확인 — 표본이 최소 개수만큼 있는지 **시작부에서** 확인하고, 없으면 멈춘다
  ② 모두     — all() 대신 쓴다. **분모를 같이 돌려주므로 0이면 '미발동'** 이 된다

규칙
  검사 결과에 분모가 안 적혀 있으면 그 검사는 믿지 않는다.
"""
from __future__ import annotations

from typing import Iterable, Sized


class 표본없음(SystemExit):
    """표본이 없으면 통과가 아니라 실행 실패다."""


def 표본확인(이름: str, 것들: Sized, 최소: int = 1, 조용히: bool = False) -> int:
    """검사를 시작하기 전에 표본이 실제로 있는지 본다.

    없으면 멈춘다. '표본 0건으로 전부 통과' 를 원천에서 막는 유일한 방법이다.
    """
    n = len(것들)
    if n < 최소:
        raise 표본없음(
            f"■ {이름}: 표본이 {n}건입니다 (최소 {최소}건 필요).\n"
            f"  표본 0건에서 나온 '통과' 는 통과가 아니라 **미발동**입니다.\n"
            f"  검사를 돌리지 않고 멈춥니다 — 통과로 기록되면 안 되기 때문입니다.")
    if not 조용히:
        print(f"  [표본 확인] {이름} {n}건")
    return n


def 모두(조건들: Iterable[bool]) -> tuple[bool, int, int]:
    """all() 대신 쓴다. (통과, 맞은수, 분모) 를 돌려준다.

    분모가 0이면 통과가 **아니다**. 호출한 쪽이 '미발동' 으로 적어야 한다.
    """
    목록 = list(조건들)
    분모 = len(목록)
    맞은수 = sum(1 for x in 목록 if x)
    return (분모 > 0 and 맞은수 == 분모), 맞은수, 분모


def 판정문(이름: str, 통과: bool, 맞은수: int, 분모: int) -> str:
    """분모를 반드시 함께 찍는다. 분모 없는 '통과' 는 읽을 수 없다."""
    if 분모 == 0:
        return f"  미발동  {이름}   검사 대상 0개 — 통과가 아닙니다"
    return f"  {'PASS' if 통과 else 'FAIL'}  {이름}   {맞은수}/{분모}"


