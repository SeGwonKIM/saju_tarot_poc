_조사 = "이가은는을를에의로와과도만처럼밖조차까지부터라도"


def _한음절_경계(문장: str, 낱말: str) -> bool:
    """한 음절 금칙어가 진짜로 그 뜻으로 쓰였는가.

    '암시' 의 암은 다른 낱말의 일부이고, '위암이' 의 암은 진짜다.
    뒤에 오는 글자가 조사이거나 한글이 아니면 낱말이 끝난 것으로 본다.
    """
    i = 0
    while (i := 문장.find(낱말, i)) != -1:
        뒤 = 문장[i + len(낱말):i + len(낱말) + 1]
        if 뒤 == "" or 뒤 in _조사 or not ("가" <= 뒤 <= "힣"):
            return True
        i += 1
    return False


def 문장검사(문장: str) -> tuple[str, str] | None:
    """(분류, 무엇이 걸렸나) 또는 None."""
    # 1층
    for 갈래, 낱말들 in 절대금지.items():
        for w in 낱말들:
            걸림 = _한음절_경계(문장, w) if len(w) == 1 else (w in 문장)
            if 걸림:
                return (f"절대금지·{갈래}", w)
    # 2층 조건부 — 낱말 + 단정어미가 같이 있을 때만
    for w, 갈래 in 조건부:
        if w in 문장 and re.search(rf"{re.escape(w)}[^.。!?]{{0,12}}{_단정어미}", 문장):
            return (f"조건부·{갈래}", f"{w} + 단정형")
    # 2층 양태
    for 무늬, 이름 in 양태:
        if re.search(무늬, 문장):
            return ("양태", 이름)
    return None


def 전체검사(문장들: list[str]) -> tuple[str, str] | None:
    for t in 문장들:
        if (r := 문장검사(t)):
            return r
    return None


def 빠진_필수문구(문장들: list[str], topics: list[str]) -> list[str]:
    """주제가 요구하는 안내 문구가 빠졌으면 그 문구를 돌려준다."""
    합친 = " ".join(문장들)
    빠짐 = []
    for t in topics:
        if t not in 필수문구:
            continue
        문구, 단서 = 필수문구[t]
        if not any(c in 합친 for c in 단서):
            빠짐.append(문구)
    return 빠짐


