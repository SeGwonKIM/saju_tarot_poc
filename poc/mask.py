# 무엇이 여전히 나가는가 — 숨기지 않고 적는다
# ══════════════════════════════════════════════════════════
나가는것 = [
    ("전사문 전체", "② 추출", "필수",
     "무엇을 말했는지 알아야 뽑는다. 위 무늬에 걸린 값은 지우고 보낸다"),
    ("이름", "② 추출", "필수", "이름을 뽑는 것이 추출의 목적이다"),
    ("생년월일시", "② 추출", "필수", "이게 없으면 사주가 없다"),
    ("출생지(시 단위)", "② 추출", "필수", "진태양시 보정에 필요하다"),
    ("원국 8글자·오행", "⑦ 리포트", "필수", "계산 결과다. 개인 식별값은 아니다"),
    ("이름", "⑦ 리포트", "**가림**", "자리표로 보내고 받아서 되돌린다"),
]

지우는것 = [x[0] for x in _무늬] + [x[0] for x in _문맥무늬]


def 흐름표() -> str:
    줄 = ["[LLM 으로 나가는 것]",
          f"  {'항목':<18}{'단계':<10}{'상태':<8}이유",
          "  " + "-" * 74]
    for 항목, 단계, 상태, 이유 in 나가는것:
        줄.append(f"  {항목:<18}{단계:<10}{상태:<8}{이유}")
    줄 += ["", "[보내기 전에 지우는 것]",
           "  " + ", ".join(지우는것),
           "  → 사주 계산에 전혀 필요 없는 값들이다."]
    return "\n".join(줄)
