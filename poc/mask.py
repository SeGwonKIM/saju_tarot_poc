"""개인정보 마스킹 계층 (검토의견 §6-1)

무엇이 문제인가
  상담 녹취에는 **음성 원본 + 전사문 + 실명 + 생년월일시 + 출생지**가 들어간다.
  그리고 이 파이프라인은 그 원문을 통째로 OpenAI(미국) API 로 보낸다.
  설계 어디에도 이 이야기가 없었다.

  ⚠ 법적 판단은 여기서 하지 않는다. 국외 이전·위탁 고지 요건은 전문가 확인이 필요하다.
     이 파일이 하는 일은 **"굳이 안 보내도 되는 것을 안 보내는 것"** 뿐이다.

무엇을 가릴 수 있고 무엇은 못 가리나 — 이걸 분명히 해야 한다

  가릴 수 있다   주민등록번호 · 전화번호 · 이메일 · 카드/계좌번호 · 상세주소
                 사주 계산에 **전혀 필요 없는 값**들이다. 보낼 이유가 없다.

  못 가린다      생년월일시 · 음/양력 · 출생지(시 단위)
                 이게 없으면 사주를 못 뽑는다. **본질적으로 나간다.**

  가릴 수 있으나 단계에 따라 다르다
                 이름 — ② 추출 단계에서는 뽑아야 하니 나간다.
                        ⑦ 리포트 생성 단계에서는 **자리표로 바꿔** 보내고
                        받아온 문장에서 되돌린다. 문장 품질에 영향이 없다.

그래서 이 파일은 정직하게 두 가지를 한다.
  ① 안 보내도 되는 것을 지운다
  ② **무엇이 여전히 나가는지 목록으로 알려 준다** (숨기지 않는다)
"""
from __future__ import annotations

import re
from dataclasses import dataclass, field

_자리표 = "〔{}{}〕"


@dataclass
class 가림결과:
    글: str
    복원표: dict[str, str] = field(default_factory=dict)
    지운것: list[tuple[str, int]] = field(default_factory=list)

    def 되돌림(self, t: str) -> str:
        for 자리, 원본 in self.복원표.items():
            t = t.replace(자리, 원본)
        return t


# 사주 계산에 전혀 필요 없는 값들.
#
# ⚠ 무늬를 **좁게** 잡는 것이 핵심이다. 넓게 잡으면 생년월일을 지워 버린다.
#    예: `\d{2,6}-\d{2,6}-\d{2,7}` 같은 계좌번호 무늬는 `1990-12-31` 도 삼킨다.
#    그래서 계좌번호는 '계좌/통장' 이라는 말이 앞에 있을 때만 지운다.
#    순서도 중요하다 — 전화번호를 계좌번호보다 먼저 봐야 한다.
_무늬 = (
    ("주민번호", r"\d{6}\s*[-–]\s*[1-4]\d{6}"),
    ("카드번호", r"\d{4}[- ]\d{4}[- ]\d{4}[- ]\d{4}"),
    ("전화번호", r"01[016-9][- ]?\d{3,4}[- ]?\d{4}"),
    ("일반전화", r"0[2-6]\d?[- ]\d{3,4}[- ]\d{4}"),
    ("이메일", r"[\w.+-]+@[\w-]+\.[\w.]+"),
    ("상세주소", r"[가-힣0-9]+(?:로|길)\s*\d+(?:[- ]\d+)?"
                 r"(?:\s*,?\s*\d+\s*동)?(?:\s*,?\s*\d+\s*호)?"),
)

# 앞에 문맥이 있어야만 지우는 것 — (이름, 문맥, 값 무늬)
_문맥무늬 = (
    ("계좌번호", r"(?:계좌|통장|입금)[^\d]{0,12}", r"\d[\d\- ]{7,}\d"),
)


def 가리기(글: str) -> 가림결과:
    """사주 계산에 필요 없는 개인정보를 자리표로 바꾼다.

    생년월일·시각 같은 숫자는 건드리지 않는다. 무늬를 좁게 잡은 이유다.
    """
    r = 가림결과(글=글)
    셈: dict[str, int] = {}
    for 이름, 무늬 in _무늬:
        def 바꾸기(m, 이름=이름):
            셈[이름] = 셈.get(이름, 0) + 1
            자리 = _자리표.format(이름, 셈[이름])
            r.복원표[자리] = m.group()
            return 자리
        r.글 = re.sub(무늬, 바꾸기, r.글)

    for 이름, 문맥, 값무늬 in _문맥무늬:
        def 바꾸기2(m, 이름=이름):
            셈[이름] = 셈.get(이름, 0) + 1
            자리 = _자리표.format(이름, 셈[이름])
            r.복원표[자리] = m.group(1)
            return m.group(0).replace(m.group(1), 자리)
        r.글 = re.sub(문맥 + f"({값무늬})", 바꾸기2, r.글)

    r.지운것 = sorted(셈.items())
    return r


def 이름가리기(이름: str | None) -> tuple[str, dict[str, str]]:
    """⑦ 리포트 생성용. 실명 대신 자리표를 보내고 받아서 되돌린다.

    리포트 문장은 "○○님은 ~" 정도로만 이름을 쓰므로 자리표여도 품질이 같다.
    """
    if not 이름:
        return "손님", {}
    자리 = "〔의뢰인〕"
    return 자리, {자리: 이름}


def 되돌리기(t: str, 표: dict[str, str]) -> str:
    for 자리, 원본 in 표.items():
        t = t.replace(자리, 원본)
    return t


